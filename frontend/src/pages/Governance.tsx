import { api, fmtTime } from '../api'
import { Card, Kpi } from '../components'
import { IconShield } from '../icons'
import { useData } from '../state'
import { SuggestionList } from './CommandCenter'

export function Governance() {
  const sugg = useData(() => api.suggestions())
  const audit = useData(() => api.audit())
  if (!sugg || !audit) return null
  const pending = sugg.filter((s) => s.status === 'pending')
  const decided = sugg.filter((s) => s.status !== 'pending')
  const v = audit.verification

  return (
    <>
      <div className="kpis" style={{ gridTemplateColumns: 'repeat(4, minmax(0, 1fr))' }}>
        <Kpi label="Pending approval" value={pending.length} tone={pending.length ? 'crit' : 'good'} foot="Recommendations awaiting a person" />
        <Kpi label="Decided today" value={decided.length} foot="Approved or dismissed" />
        <Kpi label="Audit entries" value={v.entries} foot="Append-only, hash-chained" />
        <Kpi label="Chain integrity" value={v.valid ? 'Verified' : `Broken at #${v.broken_at}`} tone={v.valid ? 'good' : 'crit'} foot="SHA-256 recomputed on load" />
      </div>
      <div className="grid-2">
        <Card title="Recommendations" hint="Generated by transparent rules; each carries its evidence">
          <SuggestionList items={[...pending, ...decided]} />
        </Card>
        <Card title={<span style={{ display: 'inline-flex', gap: 8, alignItems: 'center' }}><IconShield width={16} height={16} />Audit log</span>}
          right={<span className={`badge ${v.valid ? 'good' : 'crit'}`}>{v.valid ? 'Chain verified' : 'Tampering detected'}</span>}>
          {audit.entries.length === 0 ? <div className="muted">No decisions yet. Approve a recommendation to create the first entry.</div> : (
            <table className="table">
              <thead><tr><th>#</th><th>Time</th><th>Who</th><th>Action</th><th>Hash</th></tr></thead>
              <tbody>
                {audit.entries.map((e) => (
                  <tr key={e.seq}>
                    <td className="mono">{e.seq}</td>
                    <td className="mono">{fmtTime(e.ts)}</td>
                    <td>{e.actor}</td>
                    <td><span className="badge">{e.action}</span></td>
                    <td className="hash" title={`prev ${e.prev_hash}`}>{e.hash.slice(0, 10)}…</td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </Card>
      </div>
    </>
  )
}
